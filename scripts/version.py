"""Synchronize release manifests from pyproject.toml, the version authority."""
import argparse
import json
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    version = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]
    updates = {ROOT / "backend/app/version.py": f'"""Generated by scripts/version.py from pyproject.toml."""\nVERSION = "{version}"\n'}
    for name in ["apps/desktop/package.json", "apps/desktop/renderer/package.json", "apps/desktop/src-tauri/tauri.conf.json", "apps/desktop/package-lock.json", "apps/desktop/renderer/package-lock.json"]:
        path = ROOT / name
        data = json.loads(path.read_text())
        data["version"] = version
        if "packages" in data:
            data["packages"][""]["version"] = version
        updates[path] = json.dumps(data, indent=2) + "\n"
    path = ROOT / "apps/desktop/src-tauri/Cargo.toml"
    updates[path] = re.sub(r'(?m)^version = "[^"]+"', f'version = "{version}"', path.read_text(), count=1)
    path = ROOT / "apps/desktop/src-tauri/Cargo.lock"
    updates[path] = re.sub(r'(name = "omnidev"\nversion = ")[^"]+', lambda m: m[1]+version, path.read_text())
    stale = [str(path.relative_to(ROOT)) for path, content in updates.items() if not path.exists() or path.read_text() != content]
    if args.write:
        for path, content in updates.items():
            path.write_text(content)
    elif stale:
        raise SystemExit("Version files stale: " + ", ".join(stale) + ". Run python scripts/version.py --write")
    print(version)


if __name__ == "__main__":
    main()
